    assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark');
    assert.equal(await page.locator('.profile-avatar img').evaluate(image => image.naturalWidth > 0), true);
    assert.equal(await page.locator('.saved-address').count(), 1);
    assert.match(await page.locator('.page-heading h1').textContent(), /Ana Maria/);
    await page.setViewportSize({ width: 390, height: 844 });
