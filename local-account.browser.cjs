    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await context.route('https://viacep.com.br/**', route => {
      const second = route.request().url().includes('20040002');
      return route.fulfill({ json: second
        ? { cep: '20040-002', logradouro: 'Rua da Assembleia', bairro: 'Centro', localidade: 'Rio de Janeiro', uf: 'RJ' }
        : { cep: '01001-000', logradouro: 'Praça da Sé', bairro: 'Sé', localidade: 'São Paulo', uf: 'SP' } });
    });
    const base = `http://127.0.0.1:${server.address().port}/dist/`;
