    await page.waitForFunction(() => document.querySelector('.saved-address.selected strong')?.textContent === 'Escritório');
    assert.match(await page.locator('.saved-address.selected').textContent(), /22/);
    await page.locator('.saved-address:not(.selected) [data-address-remove]').click();
    assert.equal(await page.locator('.saved-address').count(), 1);
    assert.match(await page.locator('.header-delivery').textContent(), /20040-002/);
    await page.locator('[data-theme-toggle]').click();
    assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark');
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('theme-switching')), true);
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.site-header .brand-logo-dark')).opacity === '1');
    await page.waitForFunction(() => !document.documentElement.classList.contains('theme-switching'));
    await page.reload();
    await page.locator('[data-logout]').waitFor();
    await page.waitForTimeout(700);
